#pragma once

#include <cstddef>
#include <string>

// хеш для целых чисел; основное что выполняет хэш функция это равные ключи равные значения
// умножаем на константу чтобы близкие числа разошлись по таблице
inline size_t HashInt(const int& key) {
    size_t h = static_cast<size_t>(static_cast<unsigned int>(key)); //остаток от деления отрицательного числа в C++ тоже отрицательный и номер корзины вышел бы за границы массива
    return h * 2654435761u;//2^32 делить на холотое сечение
    //Для ёмкости равной степени двойки умножение на нечётное число только переставляет корзины местами и не меняет какие ключи сталкиваются.
}

// хеш для строк
// считаем в беззнаковом типе чтобы не было отрицательных значений
inline size_t HashString(const std::string& key) {
    size_t h = 0;
    for (char c : key) {
        h = h * 31 + static_cast<unsigned char>(c);
    }
    return h;
}

